"""Conservative graph projection and owned output management."""
from __future__ import annotations

import math
import os
from pathlib import Path
import re
from typing import Any

import yaml

HEADER = "# Generated by alertshadow; test shadow only.\n"
OPS = {"gt": ">", "lt": "<", "gte": ">=", "lte": "<="}
NUMBER = r"-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?"


class Invalid(ValueError):
    pass


def project_rule(rule: dict[str, Any], datasources: dict[str, str]) -> dict[str, Any]:
    data = rule.get("data", [])
    if not isinstance(data, list) or not all(isinstance(d, dict) for d in data):
        raise Invalid("data must be a list of nodes")
    refs = {d.get("refId"): d for d in data}
    if None in refs or len(refs) != len(data):
        raise Invalid("node references must be present and unique")
    queries = [d for d in data if d.get("datasourceUid") not in (None, "__expr__")]
    if len(queries) != 1:
        raise Invalid("exactly one datasource query is required")
    query = queries[0]
    mode = datasources.get(query["datasourceUid"])
    if mode != "prometheus":
        raise Invalid("datasource is skipped" if mode == "skip" else "unknown datasource")
    expr = query.get("model", {}).get("expr")
    if not isinstance(expr, str) or not expr.strip():
        raise Invalid("empty query expression")
    cond = refs.get(rule.get("condition"))
    if cond is None:
        raise Invalid("missing condition node")
    if cond is query:
        if not re.search(rf"(?:<=|>=|<|>)\s*{NUMBER}\s*$", expr):
            raise Invalid("direct query needs a filtering comparison")
    else:
        if cond.get("datasourceUid") != "__expr__":
            raise Invalid("condition is not an expression node")
        model = cond.get("model", {})
        kind = model.get("type")
        if kind == "math":
            match = re.fullmatch(rf"\${re.escape(str(query['refId']))}\s*(<=|>=|<|>)\s*({NUMBER})", str(model.get("expression", "")).strip())
            if not match:
                raise Invalid("unsupported math graph")
            expr = f"({expr}) {match[1]} {match[2]}"
        else:
            conditions = model.get("conditions", [])
            if not isinstance(conditions, list) or len(conditions) != 1:
                raise Invalid("exactly one evaluator is required")
            condition = conditions[0]
            if kind == "classic_conditions":
                if condition.get("query", {}).get("params") != [query["refId"]]:
                    raise Invalid("classic condition must consume the query")
                if condition.get("reducer", {}).get("type") != "last":
                    raise Invalid("only last reduction is supported")
            elif kind == "threshold":
                reduce = refs.get(model.get("expression"), {}).get("model", {})
                if (reduce.get("type"), reduce.get("reducer"), reduce.get("expression")) != ("reduce", "last", query["refId"]):
                    raise Invalid("threshold needs direct reduce-last of query")
            else:
                raise Invalid("unsupported condition type")
            evaluator = condition.get("evaluator", {})
            params = evaluator.get("params", [])
            op = OPS.get(evaluator.get("type"))
            if op is None or len(params) != 1 or isinstance(params[0], bool):
                raise Invalid("unsupported evaluator")
            value = float(params[0])
            if not math.isfinite(value):
                raise Invalid("threshold must be finite")
            # Grafana compares sample values; Prometheus fires on sample presence.
            threshold = str(int(value)) if value.is_integer() else repr(value)
            expr = f"({expr}) {op} {threshold}"
    uid = rule.get("uid")
    if not isinstance(uid, str) or not uid:
        raise Invalid("rule uid is required")
    result = {"alert": uid, "expr": expr}
    for key in ("for", "labels"):
        if key in rule:
            result[key] = rule[key]
    return result


def read_document(path: Path, env_names: list[str]) -> dict[str, Any]:
    if path.stat().st_size > 8 * 1024 * 1024:
        raise Invalid("rule file exceeds 8 MiB")
    text = path.read_text(encoding="utf-8")
    # Expand only allow-listed placeholders, before parsing with the safe loader.
    for name in env_names:
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) or name not in os.environ:
            raise Invalid("invalid or unset allow-listed environment variable")
        text = re.sub(r"\$\{" + re.escape(name) + r"\}|\$" + re.escape(name) + r"\b", lambda _: os.environ[name], text)
    try:
        doc = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise Invalid(f"invalid YAML in {path}") from exc
    if not isinstance(doc, dict):
        raise Invalid("rule document must be a mapping")
    return doc


def project_files(root: Path, config: dict[str, Any]) -> list[Path]:
    root = root.resolve()
    out = root / config.get("out", "generated")
    if out.is_symlink() or root not in out.resolve().parents:
        raise Invalid("output must be a non-symlink directory strictly inside root")
    if any(p.is_symlink() for p in [out, *out.parents] if p != root and root in p.parents):
        raise Invalid("symlink output ancestry is forbidden")
    out = out.resolve()
    patterns = config.get("rules", [])
    if not isinstance(patterns, list) or not patterns:
        raise Invalid("rules must be a nonempty list of relative globs")
    inputs: set[Path] = set()
    for pattern in patterns:
        if Path(pattern).is_absolute() or ".." in Path(pattern).parts:
            raise Invalid("rule globs must stay inside root")
        inputs.update(root.glob(pattern))
    if not inputs:
        raise Invalid("no rule inputs matched")
    outputs: dict[Path, str] = {}
    for source in sorted(inputs):
        if any(p.is_symlink() for p in [source, *source.parents] if p != root and root in p.parents) or root not in source.resolve().parents or out == source.resolve() or out in source.resolve().parents:
            raise Invalid("input must be outside output and inside root")
        doc = read_document(source, config.get("env", []))
        native = doc.get("kind") == "PrometheusRule"
        groups = doc.get("spec", {}).get("groups") if native else doc.get("groups")
        if not isinstance(groups, list):
            raise Invalid("groups must be a list")
        projected = []
        for group in groups:
            rules = []
            for rule in group.get("rules", []):
                try:
                    if native:
                        if not rule.get("alert") or not rule.get("expr"):
                            raise Invalid("native recording rules are unsupported")
                        result = {k: rule[k] for k in ("alert", "expr", "for", "labels") if k in rule}
                    else:
                        result = project_rule(rule, config.get("datasources", {}))
                    rules.append(result)
                except (Invalid, TypeError, ValueError, AttributeError) as exc:
                    if config.get("strict", True):
                        raise Invalid(f"{source}: {exc}") from exc
                    print(f"skipped {rule.get('uid', rule.get('alert', '?'))}: {exc}")
            if rules:
                projected.append({"name": group.get("name", "unnamed"), "rules": rules})
        if projected:
            target = out / source.relative_to(root)
            outputs[target] = HEADER + yaml.safe_dump({"groups": projected}, sort_keys=False)
    if not outputs:
        raise Invalid("no projectable rules")
    # Preflight everything before deleting or writing anything.
    if out.exists():
        for target in out.rglob("*"):
            if target.is_symlink():
                raise Invalid("symlink in output")
            if target in outputs and not target.read_text().startswith(HEADER):
                raise Invalid("refusing to overwrite unowned file")
    for target in list(out.rglob("*")) if out.exists() else []:
        if target.is_file() and target not in outputs and target.read_bytes().startswith(HEADER.encode()):
            target.unlink()
    for target, text in outputs.items():
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
    print(f"projected {len(outputs)} file(s)")
    return sorted(outputs)
